// Helper: generate SVG from pixel grid
function makeSvg(pixels) {
  const rects = pixels.map(([x, y]) => `<rect x="${x}" y="${y}" width="1" height="1"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" fill="none"><g fill="currentColor">${rects}</g></svg>`;
}

// Helper: make glyph entry
function g(svg, kerning = 0) {
  return { svg, rotation: 0, scale: 82, x: 0, y: 0, kerning };
}

